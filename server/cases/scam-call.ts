/** 시나리오 설계자용 요약. 사기범이 실제로 쓰는 말과 단계를 알려 준다. */
export function casesForDesigner(): string {
  return SCAM_CASES.map((c) => {
    const legit = c.legitVariant ? `\n  정상 전화라면: ${c.legitVariant}` : ''
    return `[${c.id}] ${c.name} (${c.when})
  접근: ${c.approach}
  실제 대사 예: ${c.script.map((s) => `"${s}"`).join(' / ')}
  진행: ${c.steps.join(' → ')}${legit}`
  }).join('\n\n')
}

/** 코치용 요약. 의심 신호와 정답 대응만. */
export function casesForCoach(): string {
  return SCAM_CASES.map((c) => `[${c.id}] ${c.name}
  의심 신호: ${c.signals.join(' · ')}
  정답 대응: ${c.bestResponse}`).join('\n\n')
}

export const SCAM_TYPE_OPTIONS = SCAM_CASES.map((c) => ({ id: c.id, name: c.name }))
