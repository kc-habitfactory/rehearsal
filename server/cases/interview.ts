function matchRole(text: string): RoleCase | null {
  const t = text.toLowerCase()
  return ROLE_CASES.find((r) => r.role.toLowerCase().split('·').some((k) => t.includes(k.toLowerCase())) || r.aliases.some((a) => t.includes(a.toLowerCase()))) ?? null
}

/** 시나리오 설계자용: 직무에 맞는 실제 질문 뭉치 + 트렌드 + 꼬리질문 연쇄 */
export function interviewBriefForDesigner(roleText: string): string {
  const role = matchRole(roleText)
  const roleBlock = role
    ? `[직군 매칭: ${role.role}]
실제 질문 예: ${role.realQuestions.map((q) => `"${q}"`).join(' / ')}
파고드는 지점: ${role.probes.join(' · ')}
${role.format ? `형식: ${role.format}` : ''}`
    : `[직군 매칭 없음] 입력된 직무 "${roleText}"의 실무 판단·성과·협업을 묻는 질문을 만든다. 아래 공통 질문과 꼬리질문 연쇄를 활용한다.`
  return `===== 2025~2026 면접 트렌드 =====${INTERVIEW_TRENDS}

===== 직군별 실제 질문 =====
${roleBlock}

===== 공통 질문 (직군 무관) =====
${COMMON_QUESTIONS.map((q) => `- ${q}`).join('\n')}

===== 면접관의 꼬리질문 연쇄 =====${FOLLOW_UP_CHAINS}`
}

/** 코치용: 이 직군에서 면접관이 감점하는 신호 + 좋은 답의 구조 */
export function interviewBriefForCoach(roleText: string): string {
  const role = matchRole(roleText)
  const roleBlock = role
    ? `[직군: ${role.role}] 면접관이 감점하는 답: ${role.redFlags.join(' · ')} / 파고드는 지점: ${role.probes.join(' · ')}`
    : ''
  return `${roleBlock}
${INTERVIEW_TRENDS}
${FOLLOW_UP_CHAINS}`
}
